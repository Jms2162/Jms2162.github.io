const $ = (s) => document.querySelector(s);
const el = (tag, cls, text) => {
  const n = document.createElement(tag);
  if (cls) n.className = cls;
  if (text !== undefined) n.textContent = text;
  return n;
};

const SUPPORTED = ["es", "en", "pt"];
let lang = SUPPORTED.includes(navigator.language.slice(0, 2)) ? navigator.language.slice(0, 2) : "en";
try { const saved = localStorage.getItem("lang"); if (SUPPORTED.includes(saved)) lang = saved; } catch (e) {}

const t = (k) => I18N[lang][k];
// Textos de los labs: string único u objeto {es, en}
const L = (v) => (v && typeof v === "object" && !Array.isArray(v)) ? (v[lang] || v.es || v.en || "") : v;
const fmt = (d) => new Date(d + "T00:00:00").toLocaleDateString(t("locale"), { day: "numeric", month: "short", year: "numeric" });

const labs = [...LABS].sort((a, b) => b.date.localeCompare(a.date));
const unique = (k) => [...new Set(labs.map((l) => l[k]))];
let current = null;

function fillSelect(sel, label, values, labeler) {
  const prev = sel.value;
  sel.replaceChildren(new Option(label, ""));
  values.forEach((v) => sel.append(new Option(labeler ? labeler(v) : v, v)));
  sel.value = prev;
}

function render() {
  const q = $("#q").value.trim().toLowerCase();
  const p = $("#f-plat").value, d = $("#f-dif").value;
  const list = labs.filter((l) =>
    (!p || l.platform === p) && (!d || l.difficulty === d) &&
    (!q || [L(l.title), L(l.summary), ...l.tags, ...l.tools].join(" ").toLowerCase().includes(q))
  );
  const grid = $("#grid");
  grid.replaceChildren();
  list.forEach((l) => {
    const card = el("button", "card lvl-" + l.difficulty);
    card.type = "button";
    const meta = el("div", "meta");
    meta.append(el("span", "badge dif-" + l.difficulty, t(l.difficulty)), el("span", "", l.platform + " · " + l.os));
    const tags = el("div", "tags");
    l.tags.forEach((x) => tags.append(el("span", "tag", x)));
    card.append(meta, el("h3", "", L(l.title)), el("p", "", L(l.summary)), tags, el("time", "", fmt(l.date)));
    card.onclick = () => openLab(l);
    grid.append(card);
  });
  $("#empty").hidden = list.length > 0;
}

function renderDetail(l) {
  const box = $("#detail");
  box.replaceChildren();
  const meta = el("div", "meta");
  meta.append(el("span", "badge dif-" + l.difficulty, t(l.difficulty)), el("span", "", l.platform + " · " + l.os + " · " + fmt(l.date)));
  box.append(meta, el("h2", "", L(l.title)), el("p", "", L(l.summary)));
  const tools = el("div", "tags");
  l.tools.forEach((x) => tools.append(el("span", "tag", x)));
  box.append(el("h4", "", t("tools")), tools, el("h4", "", t("steps")));
  const ol = el("ol", "steps");
  l.steps.forEach((s) => {
    const li = el("li");
    li.append(el("strong", "", L(s.title)), el("p", "", L(s.text)));
    if (s.code) { const pre = el("pre"); pre.append(el("code", "", s.code)); li.append(pre); }
    ol.append(li);
  });
  box.append(ol, el("h4", "", t("lessons")), el("p", "", L(l.lessons)));
}

function openLab(l) { current = l; renderDetail(l); $("#modal").showModal(); }

function applyLang() {
  document.documentElement.lang = lang;
  document.title = t("page_title");
  $("#meta-desc").content = t("meta_desc");
  document.querySelectorAll("[data-i18n]").forEach((n) => (n.textContent = t(n.dataset.i18n)));
  document.querySelectorAll("[data-i18n-ph]").forEach((n) => (n.placeholder = t(n.dataset.i18nPh)));
  document.querySelectorAll("[data-i18n-aria]").forEach((n) => n.setAttribute("aria-label", t(n.dataset.i18nAria)));
  document.querySelectorAll("[data-lang]").forEach((b) => b.setAttribute("aria-pressed", b.dataset.lang === lang));
  fillSelect($("#f-plat"), t("all_plat"), unique("platform"));
  fillSelect($("#f-dif"), t("all_dif"), unique("difficulty"), t);
  $("#stat-total").textContent = labs.length;
  $("#stat-plat").textContent = unique("platform").length;
  $("#stat-last").textContent = labs.length ? fmt(labs[0].date) : "—";
  $("#year").textContent = new Date().getFullYear();
  const cv = $("#cv-btn");
  cv.href = lang === "es" ? "cv-es.pdf" : "cv-en.pdf";
  cv.download = lang === "es" ? "Joaquin_Sanguinetti_CV_ES.pdf" : "Joaquin_Sanguinetti_CV_EN.pdf";
  render();
  if (current && $("#modal").open) renderDetail(current);
}

document.querySelectorAll("[data-lang]").forEach((b) => {
  b.onclick = () => {
    lang = b.dataset.lang;
    try { localStorage.setItem("lang", lang); } catch (e) {}
    applyLang();
  };
});
["input", "change"].forEach((e) => {
  $("#q").addEventListener(e, render);
  $("#f-plat").addEventListener(e, render);
  $("#f-dif").addEventListener(e, render);
});
$("#close").onclick = () => $("#modal").close();
$("#modal").addEventListener("click", (e) => { if (e.target.id === "modal") e.target.close(); });
applyLang();

// Animación de entrada: se "tipea" el prompt y después aparece el resto
function intro() {
  if (matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  const hero = $("#inicio");
  const p = hero.querySelector(".prompt");
  const full = p.textContent;
  const cursor = el("span", "cursor");
  let i = 0;
  hero.classList.add("pending");
  p.textContent = "";
  p.append(cursor);
  const tick = () => {
    p.textContent = full.slice(0, ++i);
    p.append(cursor);
    if (i < full.length) setTimeout(tick, 90);
    else setTimeout(() => hero.classList.remove("pending"), 350);
  };
  setTimeout(tick, 300);
}
intro();